using IC2.Engine.Model;

namespace IC2.Engine.MapGen;

/// <summary>Thrown when every attempt failed; the message names the checks that failed.</summary>
public sealed class MapGenerationFailed(string message, IReadOnlyList<string> problems)
    : Exception(message)
{
    /// <summary>The last attempt's named problems, for diagnostics and tests.</summary>
    public IReadOnlyList<string> Problems { get; } = problems;
}

/// <summary>
/// T294b: the deterministic generator entry point. Each attempt composes a candidate from the
/// style under a fresh attempt-derived seed stream, validates it, and the first clean candidate
/// becomes the world; exhausting the bounded attempts (20, the contract's proposal) fails naming
/// the failed checks. Generation is a pure function of (version, style, seed, size, parameters):
/// it never reads shipped data, never touches campaign RNG, and the same inputs produce the same
/// world.
/// </summary>
public static class MapGenerator
{
    /// <summary>The contract's proposed bounded retry count.</summary>
    public const int MaxAttempts = 20;

    public static GeneratedWorld Generate(string version, IMapStyle style, ulong seed, MapSize size,
        string worldId, string worldName, IReadOnlyDictionary<string, string>? parameters = null)
    {
        var empty = parameters ?? new Dictionary<string, string>();
        IReadOnlyList<string> lastProblems = Array.Empty<string>();
        var seenChecks = new SortedSet<string>();
        for (var attempt = 1; attempt <= MaxAttempts; attempt++)
        {
            var rng = MapSeedStream.For(seed, attempt);
            var map = style.Compose(rng, size, empty);
            lastProblems = MapValidator.Validate(map);
            if (lastProblems.Count == 0)
                return new GeneratedWorld(ToWorld(version, style, seed, size, worldId, worldName, map), version, seed, attempt);
            foreach (var problem in lastProblems)
                seenChecks.Add(problem.Split(':')[0]);
        }

        throw new MapGenerationFailed(
            $"map generation failed after {MaxAttempts} attempts; checks failed: {string.Join(", ", seenChecks)}",
            lastProblems);
    }

    private static World ToWorld(string version, IMapStyle style, ulong seed, MapSize size, string worldId,
        string worldName, GeneratedMap map)
    {
        var world = new World(
            GameDataSchema.CurrentVersion,
            worldId,
            worldName,
            size.Width,
            size.Height,
            new TerrainGrid(TerrainEncoding.Base64, Data: CanonicalTiles.Encode(map.Codes)),
            CanonicalTiles.Values,
            map.Nations,
            map.Cities,
            map.Armies,
            map.Fleets,
            map.TurnOrder,
            map.Relations,
            Provenance: new ProvenanceMap(new List<ProvenanceEntry>
            {
                new("_group",
                    $"designed: generated by MapGenerator {version}, style {style.Id}, seed {seed} "
                    + "(docs/tasks/T294.md); the generated world is embedded in the save and never regenerated."),
                new("seed", $"designed: generation seed {seed}, attempt provenance only; reloading never regenerates."),
            }));

        var decoded = world.Terrain.Decode(world.Width, world.Height);
        if (decoded.Length != map.Codes.Length)
            throw new InvalidOperationException("the generated terrain grid did not encode to the map size");
        return world;
    }
}
