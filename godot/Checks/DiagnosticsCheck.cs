    private void Observe(string name, string source, Action action, bool success = true, GameSession? session = null)
    {
        var before = Records().Where(r => r.GetProperty("source").GetString() == source && r.GetProperty("outcome").GetString() == "BEFORE").Select(r => r.GetProperty("operation").GetInt64()).ToHashSet();
        int observed = 0;
        AppDiagnostics.BeforeObserver = (kind, operation, producer) =>
        {
            if (producer != source) return;
            _overhead.Start();
            var inside = Records().Where(r => r.GetProperty("operation").GetInt64() == operation).ToArray();
            Check(inside.Length == 1 && inside[0].GetProperty("outcome").GetString() == "BEFORE", name + ": BEFORE persisted inside operation");
            _observed[operation] = name; observed++;
            _overhead.Stop();
        };
        int submitted = 0;
        Action<IReadOnlyList<DomainEvent>> countSubmit = _ => submitted++;
        if (session is not null) session.EventsPublished += countSubmit;
        try { action(); }
        finally { AppDiagnostics.BeforeObserver = null; if (session is not null) session.EventsPublished -= countSubmit; }
        if (session is not null) Check(submitted == 1, name + $": exactly one actual Session.Submit (count {submitted})");
        var added = Records().Where(r => r.GetProperty("source").GetString() == source && r.GetProperty("outcome").GetString() == "BEFORE" && !before.Contains(r.GetProperty("operation").GetInt64())).ToArray();
        Check(added.Length == 1 && observed == 1, name + ": exactly one real entry BEFORE");
        if (added.Length != 1) return;
        var id = added[0].GetProperty("operation").GetInt64();
        var outcomes = Records().Where(r => r.GetProperty("operation").GetInt64() == id && r.GetProperty("outcome").GetString() != "BEFORE").ToArray();
        Check(outcomes.Length == 1 && outcomes[0].GetProperty("outcome").GetString() == (success ? "AFTER" : "FAILURE"), name + ": exactly one correlated outcome");
    }

    private void CheckManagedLifetime()
    {
        var journal = AppDiagnostics.Journal;
        int registrations = AppDiagnostics.ManagedHandlerRegistrations;
        AppDiagnostics.Acquire();
        Check(ReferenceEquals(journal, AppDiagnostics.Journal) && registrations == AppDiagnostics.ManagedHandlerRegistrations, "managed hooks register once across two owners");
        AppDiagnostics.Release();
        Check(ReferenceEquals(journal, AppDiagnostics.Journal), "nested release keeps first owner's journal");
        var exceptions = Records().Count(r => Kind(r) == "Exception");
        AppDiagnostics.ProbeManagedHandlers(new InvalidOperationException("Operation failed for 'PrivateNameProbe'", new IOException("Access denied")));
        Check(Records().Count(r => Kind(r) == "Exception") == exceptions + 2, "managed unhandled/unobserved handler paths retain both causes");
        int events = 0; bool observed = false;
        EventHandler<UnobservedTaskExceptionEventArgs> observer = (_, args) => { events++; observed |= args.Observed; };
        TaskScheduler.UnobservedTaskException += observer;
        try { AbandonTask(); CollectTasks(); }
        finally { TaskScheduler.UnobservedTaskException -= observer; }
        Check(events >= 1 && !observed && Records().Count(r => Kind(r) == "Exception") > exceptions + 2, "actual unobserved subscription logs without marking task observed");
    }
    private void CheckUnregistration()
    {
        var unregistered = AppDiagnostics.ManagedHandlerUnregistrations;
        RemoveChild(_app!); _app!.QueueFree(); _app = null;
        Check(AppDiagnostics.Journal is null && AppDiagnostics.ManagedHandlerUnregistrations == unregistered + 1, "AppRoot exit unregisters managed hooks once");
        int count = Records().Length;
        AppDiagnostics.ProbeManagedHandlers(new Exception("PrivateNameProbe"));
        AbandonTask(); CollectTasks(); AppDiagnostics.Release();
        Check(Records().Length == count && AppDiagnostics.ManagedHandlerUnregistrations == unregistered + 1, "released hooks write nothing and repeated release is harmless");
    }
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static void AbandonTask() { _ = Task.FromException(new IOException("Access denied for 'PrivateNameProbe'")); }
    private static void CollectTasks() { for (int i = 0; i < 3; i++) { GC.Collect(); GC.WaitForPendingFinalizers(); } }

    private void CheckSettingsControls()
    {
        // With only the authored pack offered, the Asset pack picker is hidden.
        var picker = Walk(_app!.CurrentScreen!).OfType<OptionButton>().SingleOrDefault(o => o.Name == SettingsScreen.PackPickerName);
        int initialPack = picker?.Selected ?? -1;
        var sound = Walk(_app.CurrentScreen!).OfType<CheckBox>().Single(c => c.Name == SettingsScreen.SoundCheckName);
        bool originalSound = SettingsScreen.SoundEnabled;
        try
        {
            if (picker is { ItemCount: > 1 })
            {
                int other = (initialPack + 1) % picker.ItemCount;
                picker.Select(other); picker.EmitSignal(OptionButton.SignalName.ItemSelected, (long)other);
                var metadata = Records().Last(r => Kind(r) == "Settings").GetProperty("metadata");
                Check(SettingsScreen.SelectedPackId == picker.GetItemText(other)
                    && metadata.GetProperty("pack").GetString() == picker.GetItemText(other), "actual pack picker persists bounded selected pack context");
            }
            sound.SetPressedNoSignal(!originalSound); sound.EmitSignal(BaseButton.SignalName.Toggled, !originalSound);
            Check(SettingsScreen.SoundEnabled == !originalSound && Records().Last(r => Kind(r) == "Settings").GetProperty("metadata").GetProperty("sound").GetBoolean() == !originalSound,
                "actual sound toggle persists explicit preference");
        }
        finally
        {
            if (picker is not null) { picker.Select(initialPack); picker.EmitSignal(OptionButton.SignalName.ItemSelected, (long)initialPack); }
            sound.SetPressedNoSignal(originalSound); sound.EmitSignal(BaseButton.SignalName.Toggled, originalSound);
        }
        Check(SettingsScreen.BattleShotDelaySeconds == 1 && SettingsScreen.BattleAttackDelaySeconds == 2 && SettingsScreen.SoundEnabled == originalSound,
            "pack/sound controls preserve explicit battle pauses and restore preferences");
    }
    private static IEnumerable<Node> Walk(Node root) => root.GetChildren().SelectMany(n => new[] { n }.Concat(Walk(n)));

    private void CheckStorageFailureIsolation()
    {
        var blocked = Path.Combine(_directory, "blocked-journal");
        File.WriteAllText(blocked, "synthetic unrelated file");
        var logPath = ProjectSettings.GlobalizePath(ProjectSettings.GetSetting("debug/file_logging/log_path").AsString());
        const string warning = "Local diagnostics unavailable; gameplay continues.";
        int warningsBefore = ReadShared(logPath).Split(warning, StringSplitOptions.None).Length - 1;
        AppDiagnostics.DirectoryOverride = blocked;
        AppDiagnostics.Acquire();
        try
        {
            var session = Classical(); var reference = Classical();
            var game = AddGame(session);
            int submitted = 0; session.EventsPublished += _ => submitted++;
            game.SubmitForCheck("news"); reference.Submit("news");
            for (int i = 0; i < 20; i++) AppDiagnostics.Mark(DiagnosticEvent.Focus, "gained");
            Check(submitted == 1 && JsonSerializer.Serialize(session.State) == JsonSerializer.Serialize(reference.State), "disabled journal cannot change actual gameplay submission/state/RNG");
            var exception = new InvalidOperationException("Operation failed");
            bool preserved = false;
            try { AppDiagnostics.Operation<int>(DiagnosticEvent.Command, "check", () => throw exception); }
            catch (InvalidOperationException caught) { preserved = ReferenceEquals(exception, caught); }
            Check(preserved, "diagnostics preserves operation exception semantics");
            int warningsAfter = ReadShared(logPath).Split(warning, StringSplitOptions.None).Length - 1;
            Check(warningsAfter == warningsBefore + 1, "storage failure warns once without recursive logging");
            Check(File.ReadAllText(blocked) == "synthetic unrelated file", "failed journal never modifies unrelated target");
        }
        finally { AppDiagnostics.Release(); AppDiagnostics.DirectoryOverride = _directory; }
    }

